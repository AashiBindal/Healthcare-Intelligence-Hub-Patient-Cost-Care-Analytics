CREATE OR REPLACE TABLE FACT_PATIENT_VISITS AS
SELECT
    v.VISIT_ID,
    v.PATIENT_ID,
    v.DOCTOR_ID,
    v.FACILITY_ID,
    v.DIAGNOSIS_ID,
    v.VISIT_DATE,
    v.VISIT_TYPE,
    v.ADMISSION_STATUS,
    v.TREATMENT_STATUS,
    v.LENGTH_OF_STAY_DAYS,
    v.CONSULTATION_COST,
    v.MEDICATION_COST,
    v.LAB_COST,
    v.ROOM_COST,
    v.TOTAL_COST,
    v.INSURANCE_COVERAGE,
    v.PATIENT_PAYMENT,
    v.PATIENT_SATISFACTION,
    v.READMISSION_WITHIN_30_DAYS,
    p.FIRST_NAME,
    p.LAST_NAME,
    p.GENDER,
    p.CITY            AS PATIENT_CITY,
    p.INSURANCE_PROVIDER,
    d.DOCTOR_NAME,
    d.SPECIALTY,
    d.DEPARTMENT,
    f.FACILITY_NAME,
    f.CITY            AS FACILITY_CITY,
    f.FACILITY_TYPE,
    dg.DIAGNOSIS_NAME,
    dg.DIAGNOSIS_CATEGORY
FROM HEALTH_DB.STAGING.PATIENT_VISITS v
LEFT JOIN HEALTH_DB.STAGING.PATIENTS   p  ON v.PATIENT_ID   = p.PATIENT_ID
LEFT JOIN HEALTH_DB.STAGING.DOCTORS    d  ON v.DOCTOR_ID    = d.DOCTOR_ID
LEFT JOIN HEALTH_DB.STAGING.FACILITIES f  ON v.FACILITY_ID  = f.FACILITY_ID
LEFT JOIN HEALTH_DB.STAGING.DIAGNOSES  dg ON v.DIAGNOSIS_ID = dg.DIAGNOSIS_ID;

