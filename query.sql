USE SCHEMA HEALTH_DB.MART;

CREATE OR REPLACE VIEW VW_EXECUTIVE_KPI AS
SELECT
    COUNT(*)                            AS TOTAL_VISITS,
    COUNT(DISTINCT PATIENT_ID)          AS TOTAL_PATIENTS,
    COUNT(DISTINCT DOCTOR_ID)           AS TOTAL_DOCTORS,
    COUNT(DISTINCT FACILITY_ID)         AS TOTAL_FACILITIES,
    ROUND(SUM(TOTAL_COST), 2)           AS TOTAL_COST,
    ROUND(SUM(INSURANCE_COVERAGE), 2)   AS TOTAL_INSURANCE_COVERAGE,
    ROUND(SUM(PATIENT_PAYMENT), 2)      AS TOTAL_PATIENT_PAYMENT,
    ROUND(AVG(PATIENT_SATISFACTION), 2) AS AVG_PATIENT_SATISFACTION,
    ROUND(AVG(LENGTH_OF_STAY_DAYS), 2)  AS AVG_LENGTH_OF_STAY,
    SUM(CASE WHEN READMISSION_WITHIN_30_DAYS = 'Yes' THEN 1 ELSE 0 END) AS TOTAL_READMISSIONS
FROM HEALTH_DB.CURATED.FACT_PATIENT_VISITS;

CREATE OR REPLACE VIEW VW_MONTHLY_VISITS AS
SELECT
    DATE_TRUNC('MONTH', VISIT_DATE)     AS VISIT_MONTH,
    COUNT(*)                            AS TOTAL_VISITS,
    ROUND(SUM(TOTAL_COST), 2)           AS TOTAL_COST,
    ROUND(AVG(PATIENT_SATISFACTION), 2) AS AVG_SATISFACTION
FROM HEALTH_DB.CURATED.FACT_PATIENT_VISITS
GROUP BY 1
ORDER BY 1;

CREATE OR REPLACE VIEW VW_DIAGNOSIS_ANALYTICS AS
SELECT
    DIAGNOSIS_NAME,
    DIAGNOSIS_CATEGORY,
    COUNT(*)                            AS TOTAL_VISITS,
    ROUND(AVG(TOTAL_COST), 2)           AS AVG_COST,
    ROUND(AVG(LENGTH_OF_STAY_DAYS), 2)  AS AVG_LENGTH_OF_STAY,
    ROUND(AVG(PATIENT_SATISFACTION), 2) AS AVG_SATISFACTION
FROM HEALTH_DB.CURATED.FACT_PATIENT_VISITS
GROUP BY 1, 2
ORDER BY TOTAL_VISITS DESC;

CREATE OR REPLACE VIEW VW_FACILITY_ANALYTICS AS
SELECT
    FACILITY_NAME,
    FACILITY_CITY,
    FACILITY_TYPE,
    COUNT(VISIT_ID)                     AS TOTAL_VISITS,
    ROUND(SUM(TOTAL_COST), 2)           AS TOTAL_COST,
    ROUND(AVG(TOTAL_COST), 2)           AS AVG_COST_PER_VISIT,
    ROUND(AVG(PATIENT_SATISFACTION), 2) AS AVG_SATISFACTION,
    ROUND(AVG(LENGTH_OF_STAY_DAYS), 2)  AS AVG_LENGTH_OF_STAY
FROM HEALTH_DB.CURATED.FACT_PATIENT_VISITS
GROUP BY 1, 2, 3
ORDER BY TOTAL_VISITS DESC;

CREATE OR REPLACE VIEW VW_VISIT_TYPE_DISTRIBUTION AS
SELECT
    VISIT_TYPE,
    COUNT(*)                            AS TOTAL_VISITS,
    ROUND(AVG(TOTAL_COST), 2)           AS AVG_VISIT_COST,
    ROUND(AVG(PATIENT_SATISFACTION), 2) AS AVG_SATISFACTION,
    ROUND(AVG(LENGTH_OF_STAY_DAYS), 2)  AS AVG_LENGTH_OF_STAY
FROM HEALTH_DB.CURATED.FACT_PATIENT_VISITS
GROUP BY 1
ORDER BY TOTAL_VISITS DESC;

CREATE OR REPLACE VIEW VW_TREATMENT_ANALYTICS AS
SELECT
    TREATMENT_STATUS,
    COUNT(*)                            AS TOTAL_VISITS,
    ROUND(AVG(TOTAL_COST), 2)           AS AVG_COST,
    ROUND(AVG(PATIENT_SATISFACTION), 2) AS AVG_SATISFACTION
FROM HEALTH_DB.CURATED.FACT_PATIENT_VISITS
GROUP BY 1
ORDER BY TOTAL_VISITS DESC;

CREATE OR REPLACE VIEW VW_ADMISSION_STATUS_ANALYTICS AS
SELECT
    ADMISSION_STATUS,
    COUNT(*)                            AS TOTAL_VISITS,
    ROUND(AVG(TOTAL_COST), 2)           AS AVG_COST
FROM HEALTH_DB.CURATED.FACT_PATIENT_VISITS
GROUP BY 1
ORDER BY TOTAL_VISITS DESC;

CREATE OR REPLACE VIEW VW_PATIENT_VISIT_TYPE_ANALYSIS AS
SELECT
    VISIT_TYPE,
    COUNT(VISIT_ID)                     AS TOTAL_VISITS,
    ROUND(AVG(TOTAL_COST), 2)           AS AVG_VISIT_COST,
    ROUND(AVG(PATIENT_SATISFACTION), 2) AS AVG_SATISFACTION,
    ROUND(AVG(LENGTH_OF_STAY_DAYS), 2)  AS AVG_LENGTH_OF_STAY
FROM HEALTH_DB.CURATED.FACT_PATIENT_VISITS
GROUP BY 1
ORDER BY AVG_VISIT_COST DESC;

CREATE OR REPLACE VIEW VW_DOCTOR_ANALYTICS AS
SELECT
    DOCTOR_NAME,
    SPECIALTY,
    DEPARTMENT,
    COUNT(VISIT_ID)                     AS TOTAL_VISITS,
    ROUND(AVG(TOTAL_COST), 2)           AS AVG_COST_PER_VISIT,
    ROUND(AVG(PATIENT_SATISFACTION), 2) AS AVG_SATISFACTION,
    SUM(CASE WHEN READMISSION_WITHIN_30_DAYS = 'Yes' THEN 1 ELSE 0 END) AS TOTAL_READMISSIONS
FROM HEALTH_DB.CURATED.FACT_PATIENT_VISITS
GROUP BY 1, 2, 3
ORDER BY TOTAL_VISITS DESC;

CREATE OR REPLACE VIEW VW_READMISSION_ANALYTICS AS
SELECT
    DIAGNOSIS_CATEGORY,
    DIAGNOSIS_NAME,
    COUNT(*)                            AS TOTAL_VISITS,
    SUM(CASE WHEN READMISSION_WITHIN_30_DAYS = 'Yes' THEN 1 ELSE 0 END) AS READMISSIONS,
    ROUND(
        100.0 * SUM(CASE WHEN READMISSION_WITHIN_30_DAYS = 'Yes' THEN 1 ELSE 0 END) / COUNT(*),
        2
    )                                   AS READMISSION_RATE_PCT
FROM HEALTH_DB.CURATED.FACT_PATIENT_VISITS
GROUP BY 1, 2
ORDER BY READMISSION_RATE_PCT DESC;

