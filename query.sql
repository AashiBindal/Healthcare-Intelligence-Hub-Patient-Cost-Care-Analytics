USE SCHEMA HEALTH_DB.STAGING;

CREATE OR REPLACE TABLE PATIENTS AS
SELECT
    TRIM(PATIENT_ID)                    AS PATIENT_ID,
    TRIM(FIRST_NAME)                    AS FIRST_NAME,
    TRIM(LAST_NAME)                     AS LAST_NAME,
    INITCAP(TRIM(GENDER))               AS GENDER,
    DATE_OF_BIRTH,
    INITCAP(TRIM(CITY))                 AS CITY,
    TRIM(INSURANCE_PROVIDER)            AS INSURANCE_PROVIDER,
    REGISTRATION_DATE
FROM HEALTH_DB.RAW.PATIENTS_RAW
WHERE PATIENT_ID IS NOT NULL;

CREATE OR REPLACE TABLE DOCTORS AS
SELECT
    TRIM(DOCTOR_ID)                     AS DOCTOR_ID,
    TRIM(DOCTOR_NAME)                   AS DOCTOR_NAME,
    INITCAP(TRIM(SPECIALTY))            AS SPECIALTY,
    EXPERIENCE_YEARS,
    INITCAP(TRIM(DEPARTMENT))           AS DEPARTMENT
FROM HEALTH_DB.RAW.DOCTORS_RAW
WHERE DOCTOR_ID IS NOT NULL;

CREATE OR REPLACE TABLE FACILITIES AS
